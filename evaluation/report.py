"""Collect every benchmark result into one comparison.

Reads ``evaluation_results/pipeline_*.json`` (and ``vectors_*.json``,
``stores_*.json`` when present) and writes ``evaluation_results/summary.md``
and ``evaluation_results/summary.csv``.

Agreement with the baseline is reported as *overlap@6*: the share of the six
passages the baseline hands to the answering model that a configuration also
hands to it, averaged over the twenty questions. It says how much a change
alters what the model reads, not whether the result is better or worse --
there are no labelled answers to measure that against.

    .venv\\Scripts\\python.exe -m evaluation.report [--baseline LABEL]
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIRECTORY = PROJECT_ROOT / "evaluation_results"

#: Stages shown in the breakdown, in pipeline order.
STAGES = ["embed_query", "search_by_meaning", "fetch_dense_passages", "search_by_wording",
          "fusion", "rerank", "build_prompt", "retrieval_total"]


def latest_runs(pattern: str) -> dict[str, dict]:
    """The most recent result file per label (later runs supersede earlier ones)."""
    runs: dict[str, dict] = {}
    for path in sorted(RESULTS_DIRECTORY.glob(pattern)):
        data = json.loads(path.read_text(encoding="utf-8"))
        data["_file"] = path.name
        key = data.get("label") or data.get("model_id")
        runs[key] = data
    return runs


def overlap(ids: list[int], reference: list[int], k: int) -> float | None:
    if not reference:
        return None
    return len(set(ids[:k]) & set(reference[:k])) / min(k, len(reference))


def agreement(run: dict, baseline: dict) -> dict:
    """Mean overlap of each stage's output with the baseline's, over all queries."""
    result = {}
    for stage, k in [("final", 6), ("fused", 24), ("dense", 40)]:
        values = []
        for query_id, outputs in run["retrieval_outputs"].items():
            reference = baseline["retrieval_outputs"].get(query_id, {}).get(stage, [])
            value = overlap(outputs.get(stage, []), reference, k)
            if value is not None:
                values.append(value)
        result[f"{stage}@{k}"] = sum(values) / len(values) if values else None
    return result


def fmt(value, digits=1) -> str:
    if value is None:
        return "–"
    return f"{value:,.{digits}f}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--baseline", default="baseline")
    arguments = parser.parse_args()

    pipelines = latest_runs("pipeline_*.json")
    if arguments.baseline not in pipelines:
        raise SystemExit(f"no run labelled {arguments.baseline!r} in {RESULTS_DIRECTORY}")
    baseline = pipelines[arguments.baseline]
    ordered = [arguments.baseline] + sorted(k for k in pipelines if k != arguments.baseline)

    lines = ["# Performance evaluation — summary", "",
             "Generated by `python -m evaluation.report` from the JSON files in this folder.",
             f"Machine: {baseline['machine'].get('gpu', 'CPU')}, "
             f"{baseline['machine'].get('cpu_cores_logical', '?')} logical CPU cores, "
             f"{baseline['machine'].get('ram_gib', '?')} GiB RAM; "
             f"torch {baseline['machine']['torch']}, "
             f"sentence-transformers {baseline['machine']['sentence_transformers']}.", "",
             "Every configuration: warm-up passes discarded, then timed passes over all "
             "questions; values are per question, in milliseconds.", ""]

    # --- retrieval stages ---------------------------------------------------
    lines += ["## Retrieval stages (median ms; p95 in brackets)", "",
              "| configuration | " + " | ".join(STAGES) + " | overlap@6 vs baseline |",
              "|---|" + "---:|" * (len(STAGES) + 1)]
    csv_rows = []
    for label in ordered:
        run = pipelines[label]
        summary = run["stage_summary_ms"]
        cells = []
        for stage in STAGES:
            s = summary.get(stage)
            cells.append(f"{fmt(s['median'], 2 if s and s['median'] < 10 else 0)} "
                         f"({fmt(s['p95'], 2 if s and s['p95'] < 10 else 0)})" if s else "–")
        agree = agreement(run, baseline)
        lines.append(f"| {label} | " + " | ".join(cells) + f" | {fmt(agree['final@6'] * 100, 0)} % |"
                     if agree["final@6"] is not None else f"| {label} | " + " | ".join(cells) + " | – |")
        row = {"configuration": label, "file": run["_file"]}
        for stage in STAGES:
            if stage in summary:
                row[f"{stage}_median_ms"] = round(summary[stage]["median"], 3)
                row[f"{stage}_p95_ms"] = round(summary[stage]["p95"], 3)
        row.update({f"overlap_{k}": round(v, 3) for k, v in agree.items() if v is not None})
        csv_rows.append(row)

    # --- share of retrieval time ---------------------------------------------
    lines += ["", "## Where retrieval time goes (share of the median total)", "",
              "| configuration | " + " | ".join(STAGES[:-1]) + " |",
              "|---|" + "---:|" * (len(STAGES) - 1)]
    for label in ordered:
        summary = pipelines[label]["stage_summary_ms"]
        total = sum(summary[s]["median"] for s in STAGES[:-1] if s in summary) or 1
        lines.append(f"| {label} | " + " | ".join(
            f"{summary[s]['median'] / total * 100:.1f} %" if s in summary else "–"
            for s in STAGES[:-1]) + " |")

    # --- answering models ----------------------------------------------------
    llm_runs = [label for label in ordered if pipelines[label].get("llm_summary")]
    if llm_runs:
        lines += ["", "## Answering model (per answer)", "",
                  "| configuration | model | on GPU | first token (ms) | total (ms) | "
                  "prompt tokens | prompt tok/s | output tokens | output tok/s |",
                  "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for label in llm_runs:
            run = pipelines[label]
            s = run["llm_summary"]
            residency = run.get("ollama_residency") or {}
            share = residency.get("share_on_gpu")
            lines.append(
                f"| {label} | {run['configuration']['llm']} | "
                f"{fmt(share * 100, 0) + ' %' if share is not None else '–'} | "
                f"{fmt(s['first_token_ms']['median'], 0)} | {fmt(s['total_ms']['median'], 0)} | "
                f"{fmt(s['prompt_tokens']['median'], 0)} | {fmt(s['prompt_tokens_per_s']['median'], 0)} | "
                f"{fmt(s['output_tokens']['median'], 0)} | {fmt(s['output_tokens_per_s']['median'], 1)} |")
            for row in csv_rows:
                if row["configuration"] == label:
                    row.update({
                        "llm": run["configuration"]["llm"],
                        "llm_share_on_gpu": share,
                        "llm_first_token_median_ms": round(s["first_token_ms"]["median"], 1),
                        "llm_total_median_ms": round(s["total_ms"]["median"], 1),
                        "llm_output_tokens_per_s_median": round(s["output_tokens_per_s"]["median"], 2),
                    })

    # --- re-embedding throughput ----------------------------------------------
    vectors = latest_runs("vectors_*.json")
    if vectors:
        lines += ["", "## Re-embedding the corpus", "",
                  "| model | params (M) | dims | passages/s | full re-embed (min) | peak GPU (GiB) |",
                  "|---|---:|---:|---:|---:|---:|"]
        for model_id, record in vectors.items():
            lines.append(f"| {model_id} | {fmt(record['parameters_millions'], 0)} | "
                         f"{record['dimensions']} | {fmt(record['passages_per_second'], 0)} | "
                         f"{fmt(record['encode_seconds'] / 60, 1)} | "
                         f"{fmt(record['peak_gpu_memory_gib'], 2)} |")

    lines += ["", "## Files", ""] + [f"- `{pipelines[label]['_file']}` ({label})" for label in ordered]
    (RESULTS_DIRECTORY / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    fieldnames = sorted({key for row in csv_rows for key in row},
                        key=lambda k: (k not in ("configuration", "file"), k))
    with open(RESULTS_DIRECTORY / "summary.csv", "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(csv_rows)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
